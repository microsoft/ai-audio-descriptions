#!/bin/bash

# AI Audio Descriptions - Automated Azure Setup Script
# This script creates all the required Azure resources and generates the .env file
# Prerequisites: Azure CLI installed and logged in (az login)

set -e  # Exit on any error

# Configuration
RESOURCE_GROUP_NAME="rg-ai-audio-descriptions"
LOCATION="westus"  # Can be changed to swedencentral or australiaeast
NAME_PREFIX="aiad"

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

echo -e "${BLUE}🚀 AI Audio Descriptions - Automated Azure Setup${NC}"
echo -e "${BLUE}====================================================${NC}"
echo

# Check if Azure CLI is installed
if ! command -v az &> /dev/null; then
    echo -e "${RED}❌ Azure CLI is not installed. Please install it first:${NC}"
    echo "https://docs.microsoft.com/en-us/cli/azure/install-azure-cli"
    exit 1
fi

# Check if user is logged in
if ! az account show &> /dev/null; then
    echo -e "${RED}❌ You are not logged in to Azure. Please run 'az login' first.${NC}"
    exit 1
fi

# Get subscription info
SUBSCRIPTION_ID=$(az account show --query "id" -o tsv)
SUBSCRIPTION_NAME=$(az account show --query "name" -o tsv)
echo -e "${GREEN}✅ Logged in to Azure${NC}"
echo -e "   Subscription: ${SUBSCRIPTION_NAME} (${SUBSCRIPTION_ID})"
echo

# Prompt for confirmation
echo -e "${YELLOW}⚠️  This script will create the following resources in your Azure subscription:${NC}"
echo "   • Resource Group: ${RESOURCE_GROUP_NAME}"
echo "   • Location: ${LOCATION}"
echo "   • AI Services resource (with GPT-4o model deployment)"
echo "   • Storage Account (with audio-description container and CORS)"
echo
read -p "Do you want to continue? (y/N): " -n 1 -r
echo
if [[ ! $REPLY =~ ^[Yy]$ ]]; then
    echo -e "${YELLOW}❌ Setup cancelled.${NC}"
    exit 1
fi

echo -e "${BLUE}📦 Creating Azure resources...${NC}"
echo

# Create resource group
echo -e "${YELLOW}Creating resource group...${NC}"
if az group show --name "$RESOURCE_GROUP_NAME" &> /dev/null; then
    echo -e "${GREEN}✅ Resource group already exists: ${RESOURCE_GROUP_NAME}${NC}"
else
    az group create --name "$RESOURCE_GROUP_NAME" --location "$LOCATION"
    echo -e "${GREEN}✅ Created resource group: ${RESOURCE_GROUP_NAME}${NC}"
fi

# Deploy Bicep template
echo -e "${YELLOW}Deploying Azure resources (this may take 5-10 minutes)...${NC}"
DEPLOYMENT_OUTPUT=$(az deployment group create \
    --resource-group "$RESOURCE_GROUP_NAME" \
    --template-file "./deploy/main.bicep" \
    --parameters resourceGroupName="$RESOURCE_GROUP_NAME" location="$LOCATION" namePrefix="$NAME_PREFIX" \
    --query "properties.outputs" \
    --output json)

if [ $? -ne 0 ]; then
    echo -e "${RED}❌ Failed to deploy Azure resources.${NC}"
    exit 1
fi

echo -e "${GREEN}✅ Azure resources deployed successfully!${NC}"

# Extract output values
AI_SERVICES_NAME=$(echo "$DEPLOYMENT_OUTPUT" | jq -r '.aiServicesName.value')
AI_SERVICES_REGION=$(echo "$DEPLOYMENT_OUTPUT" | jq -r '.aiServicesRegion.value')
OPENAI_ACCOUNT_NAME=$(echo "$DEPLOYMENT_OUTPUT" | jq -r '.openAiAccountName.value')
STORAGE_ACCOUNT_NAME=$(echo "$DEPLOYMENT_OUTPUT" | jq -r '.storageAccountName.value')
GPT_DEPLOYMENT_NAME=$(echo "$DEPLOYMENT_OUTPUT" | jq -r '.gptDeploymentName.value')

# Get secrets using Azure CLI
echo -e "${YELLOW}Retrieving access keys...${NC}"
AI_SERVICES_KEY=$(az cognitiveservices account keys list --name "$AI_SERVICES_NAME" --resource-group "$RESOURCE_GROUP_NAME" --query "key1" --output tsv)
OPENAI_KEY=$(az cognitiveservices account keys list --name "$OPENAI_ACCOUNT_NAME" --resource-group "$RESOURCE_GROUP_NAME" --query "key1" --output tsv)
STORAGE_ACCOUNT_KEY=$(az storage account keys list --account-name "$STORAGE_ACCOUNT_NAME" --resource-group "$RESOURCE_GROUP_NAME" --query "[0].value" --output tsv)

# Generate SAS token for the container (valid for 1 year)
echo -e "${YELLOW}Generating SAS token...${NC}"
# Cross-platform date calculation (works on both macOS and Linux)
if [[ "$OSTYPE" == "darwin"* ]]; then
    # macOS
    EXPIRY_DATE=$(date -u -v+1y '+%Y-%m-%dT%H:%MZ')
else
    # Linux
    EXPIRY_DATE=$(date -u -d "1 year" '+%Y-%m-%dT%H:%MZ')
fi
SAS_TOKEN=$(az storage container generate-sas \
    --account-name "$STORAGE_ACCOUNT_NAME" \
    --account-key "$STORAGE_ACCOUNT_KEY" \
    --name "audio-description" \
    --permissions acdlrw \
    --expiry "$EXPIRY_DATE" \
    --output tsv)

echo -e "${GREEN}✅ SAS token generated${NC}"

# Create .env file
echo -e "${YELLOW}Creating .env file...${NC}"
cat > .env << EOF
# AI Audio Descriptions Environment Configuration
# Generated by automated setup script on $(date)

# Azure AI Services (for Content Understanding, Speech, etc.)
VITE_AI_SERVICES_RESOURCE=${AI_SERVICES_NAME}
VITE_AI_SERVICES_KEY=${AI_SERVICES_KEY}
VITE_AI_SERVICES_REGION=${AI_SERVICES_REGION}

# Azure OpenAI (for GPT models)
VITE_OPENAI_RESOURCE=${OPENAI_ACCOUNT_NAME}
VITE_OPENAI_KEY=${OPENAI_KEY}
VITE_OPENAI_REGION=${AI_SERVICES_REGION}

# Storage
VITE_STORAGE_ACCOUNT=${STORAGE_ACCOUNT_NAME}
VITE_BLOB_SAS_TOKEN=${SAS_TOKEN}

# GPT Model
VITE_GPT_DEPLOYMENT=${GPT_DEPLOYMENT_NAME}
EOF

echo -e "${GREEN}✅ Created .env file with all configuration${NC}"
echo

# Display summary
echo -e "${GREEN}🎉 Setup Complete!${NC}"
echo -e "${GREEN}==================${NC}"
echo
echo -e "${BLUE}📋 Summary of created resources:${NC}"
echo "   • Resource Group: ${RESOURCE_GROUP_NAME}"
echo "   • AI Services: ${AI_SERVICES_NAME}"
echo "   • OpenAI Account: ${OPENAI_ACCOUNT_NAME}"
echo "   • GPT Deployment: ${GPT_DEPLOYMENT_NAME}"
echo "   • Storage Account: ${STORAGE_ACCOUNT_NAME}"
echo "   • Container: audio-description (with CORS enabled)"
echo
echo -e "${BLUE}🏃‍♂️ Next steps:${NC}"
echo "   1. Run: npm install"
echo "   2. Run: npm run dev"
echo "   3. Open: http://localhost:5173"
echo
echo -e "${GREEN}✨ You're ready to go! Enjoy using AI Audio Descriptions!${NC}"